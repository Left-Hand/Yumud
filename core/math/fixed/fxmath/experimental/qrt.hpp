// =====================================================================
// qrt.hpp — 定点数四次根 (quartic root) 与逆四次根设计草案
// =====================================================================
//
// 目标：仿照 sqrt.hpp 中 IqSqrtIntermediate 的思路（规范化 + 查表初值 +
// 牛顿迭代），为 fixed<Q,T> 提供单趟（single-pass）计算 x^(1/4) 与
// x^(-1/4) 的实现，而不是简单地调用两次 sqrt/inv_sqrt 的组合版本。
//
// 本文件当前只写设计思路（注释 / 伪代码），尚未实现，用于先跟
// scratchpad 里的 Python 原型脚本对齐验证，确认无误后再补全 C++ 代码。
//
// ---------------------------------------------------------------------
// 1. 与 sqrt 的核心差异：规范化的"块大小"必须是 4 位而不是 2 位
// ---------------------------------------------------------------------
//
// sqrt.hpp::from_u32 之所以每次按 2 bit 为单位左移尾数做规范化，是因为
//     sqrt(4 * m) = 2 * sqrt(m)          —— 精确的整数位移关系
// 4 是完全平方数，2 bit 的输入位移 <=> 1 bit 的输出位移，位移换算是精确的
// (不引入无理数因子)。若位移不是 2 的整数倍，sqrt(2*m) = sqrt(2)*sqrt(m)
// 会引入 √2 这个无理数，无法用整数位移表示，因此原实现从不做奇数位移
// (只有编译期针对 (32-Q) 奇偶性的一次性修正)。
//
// 同理，四次根需要：
//     qrt(16 * m) = 2 * qrt(m)           —— 16 = 2^4 是完全4次幂
// 即数据相关的规范化位移必须是 4 bit 的整数倍，才能保证"输入位移 -> 输出
// 位移"仍然是精确的整数次幂关系。因此：
//   - 运行时规范化循环：每次左移 4 bit（而不是 2 bit），
//     shifts_needed = leading_zeros / 4；
//   - 编译期奇偶(这里是"四元"对齐)修正：需要修正的是 (32 - Q) mod 4，
//     可能的余数 r ∈ {0,1,2,3}，而不再只是 {0,1}。
//     若 r != 0，需要在规范化前先对输入做一次 r bit 的预左移（编译期常量，
//     只依赖 Q，不依赖运行时数据），并要求输入寄存器高 r 位为 0（即该
//     Q 格式本身要为此预留 headroom —— 这与原 sqrt 实现对奇数 (32-Q) 做
//     单 bit 预左移时隐含的假设是一致的，非四次根新引入的限制）。
//
// 结论：mantissa（规范化后的尾数）落入的"canonical range"顶端 1 bit
// 位置会分布在 bit 28~31（跨度为 16 倍，即 m ∈ [1/16, 1)），
// 比 sqrt 版本的 bit 30~31（跨度 4 倍，m ∈ [1/4, 1)）更宽。
// 但由于 m^(1/4) 在该区间的输出跨度恒为 2 倍（(1/16)^(-1/4) = 2，
// 1^(-1/4) = 1），最终 Newton 迭代要逼近的目标值范围仍然和 sqrt 版本
// 一样落在 (1, 2] —— 这一点和 sqrt 版本的 (1,2] 完全对称，说明本设计
// 的"位移块大小 = 2^幂次的倒数"这一推广思路是自洽的。
//
// ---------------------------------------------------------------------
// 2. 牛顿迭代公式（逆四次根）
// ---------------------------------------------------------------------
//
// 目标：给定规范化后的尾数 x（UQ0.32，x ∈ [1/16, 1)），求
//     g ≈ x^(-1/4)
//
// 对 f(g) = g^-4 - x 用牛顿法（这是 sqrt.hpp 里 g' = g*(1.5 - x/2*g^2)
// 公式在 p=2 情形下的推广，通用 p 次逆根迭代公式为
//     g' = g/p * (p + 1 - x * g^p)
// ）：
//     p = 4:
//     g' = g * (1.25 - 0.25 * x * g^4)
//
// 对照 sqrt.hpp 里的写法（p=2）：
//     g' = g * (1.5  - 0.5  * x * g^2)
//
// 收敛阶数仍是二阶（每次迭代有效位数翻倍），与 p 无关，因此预期同样
// 只需 2~3 次迭代即可达到 IQ32 精度。但每次迭代需要算 g^2 再平方得到
// g^4，比 sqrt 版本多一次平方运算和一次乘法，单次迭代的乘法数从 3 次
// (sqrt: mul(x,g) -> mul(., g) -> mul(g, .)) 增至约 5 次
// (g^2, g^4=sq(g^2), x*g^4, g*(常数-...))。
//
// 直接的四次根：qrt(x) = x * x^(-1/4)^3 = x^(-1/4) 的倒数处理方式与
// sqrt.hpp 保持一致 —— 先算逆四次根 g ≈ x^(-1/4)，需要正四次根时再
// 乘回 x 一次得到 x^(3/4)... 这是错的，正确关系是:
//     x^(1/4) = x * x^(-3/4) 不便；更直接: x^(1/4) = x^(-1/4) 的倒数，
//     也可写成 x^(1/4) = (x^(-1/4))^-1，但取倒数不便于定点运算。
// 更好的方式（与 sqrt.hpp 完全对称）：
//     x^(1/2) = x * x^(-1/2)          （sqrt.hpp 用的正是这个恒等式）
//     x^(1/4) = x^(1/2) * x^(-1/4) 的平方根关系不直接……
// 因此正四次根改用如下恒等式（已在 Python 脚本中验证，见下方 §4）：
//     x^(1/4) = x * g^3         其中 g = x^(-1/4)
// 即 x^(1/4) = x * x^(-3/4) = x * (x^(-1/4))^3。
// 用规范化后的尾数 m 和迭代收敛值 g（同一个 g，两种策略复用同一次牛顿
// 迭代结果）即可，只是 QUART 策略最后多一步 g -> g^3 再乘 m。
//
// ---------------------------------------------------------------------
// 3. 初值查表
// ---------------------------------------------------------------------
//
// sqrt.hpp 用 IQ14SQRT_LOOKUP，以尾数高 7 bit 为索引（覆盖跨度 4 倍的
// 区间）。四次根尾数区间跨度是 16 倍，若仍用 7 bit 索引，每个桶覆盖的
// 相对误差会更大 —— 需要以下两者之一：
//   (a) 扩大索引位宽（例如 9 bit，512 项），或
//   (b) 保持类似位宽但多迭代 1 次以补偿更粗的初值。
// 本文件暂不生成正式查表，Python 原型里先用浮点 pow(m, -0.25) 当作
// "理想初值"，只验证迭代公式和收敛所需次数，之后再仿照
// IQ14SQRT_LOOKUP 的生成方式产出定点查找表。
//
// ---------------------------------------------------------------------
// 4. 待 Python 脚本验证的问题清单
// ---------------------------------------------------------------------
//   [1] 规范化 + 指数记账：mantissa^(power) * 2^exponent 是否精确等于
//       原始 x^(power)（对所有 Q ∈ [0,31] 及所有 4 种余数类都成立）。
//   [2] 逆四次根牛顿迭代 g' = g*(1.25 - 0.25*x*g^4) 从粗略初值出发，
//       几次迭代可以收敛到 ~2^-30 相对精度。
//   [3] 正四次根恒等式 x^(1/4) = x * g^3 (g = x^(-1/4)) 数值上是否
//       和直接算 pow(x, 0.25) 吻合。
//   [4] 32 bit 位宽定点乘法（模拟 mul32hu，只保留高 32 位）在计算
//       g^2 -> g^4 -> x*g^4 这条更长的乘法链上，精度损失是否可接受，
//       还是需要提升中间精度（例如借用 64 bit 甚至 128 bit 中间乘法）。
//
// 待以上 4 点都在 Python 脚本里得到确认后，再把 IqSqrtIntermediate 的
// 结构套用过来，正式实现 QuartNormStrategy / IqQuartIntermediate /
// qrt32u / inv_qrt32u 等，与 sqrt.hpp 保持同样的命名与代码风格。
